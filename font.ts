/** Draw a text string. x,y = top-left of the em box; size = em height in final pixels. */
export function drawText(
  put: (x1: number, y1: number, x2: number, y2: number, r: number) => void,
  text: string, x: number, y: number, size: number, strokeW: number, tracking = 1.6,
) {
  const s = size / 10;
  let cx = x;
  for (const ch of text) {
    const glyph = G[ch] ?? G["?"];
    const adv = ch === " " ? 3.4 : ch === "I" || ch === "'" || ch === "." || ch === "," || ch === "!" ? 5 : ch === "-" ? 6 : 7;
    for (const stroke of glyph) {
      for (let i = 0; i + 1 < stroke.length; i++) {
        const [x1, y1] = stroke[i], [x2, y2] = stroke[i + 1];
        put(cx + x1 * s, y + (10 - y1) * s, cx + x2 * s, y + (10 - y2) * s, strokeW / 2);
      }
    }
    cx += adv * s + tracking;
  }
  return cx - tracking; // pen x after the string
}

/** Measure the width of a string at the given size. */
export function textWidth(text: string, size: number, tracking = 1.6): number {
  const s = size / 10;
  let w = 0;
  for (const ch of text) {
    const adv = ch === " " ? 3.4 : ch === "I" || ch === "'" || ch === "." || ch === "," || ch === "!" ? 5 : ch === "-" ? 6 : 7;
    w += adv * s + tracking;
  }
  return w - tracking;
}
